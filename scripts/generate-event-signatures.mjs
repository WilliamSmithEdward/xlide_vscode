#!/usr/bin/env node
// Writes src/analyzer/host/eventSignaturesData.ts: each Office class's events
// with their parameters as VBA declares them, ByVal where the library passes
// by value. A handler must match its event's declaration, or the VBE refuses
// the module (issue #195).
//
//     node scripts/generate-event-signatures.mjs
//
// The inputs are reference/<library>/eventSources.json, which
// scripts/dump-event-sources.py reads straight from a type library:
//
//     python scripts/dump-event-sources.py "<Office16>/EXCEL.EXE" reference/excel/eventSources.json
//     python scripts/dump-event-sources.py "<Office16>/MSWORD.OLB" reference/word/eventSources.json
//     python scripts/dump-event-sources.py "<Office16>/MSPPT.OLB" reference/powerpoint/eventSources.json
//     python scripts/dump-event-sources.py "<Office root>/vfs/System/FM20.DLL" reference/msforms/eventSources.json
//
// reference/ is not committed; the generated file is. Access keeps its events
// in its own object model, generated from the same dump.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIBRARIES = [
	['excel', 'Excel'],
	['word', 'Word'],
	['powerpoint', 'PowerPoint'],
	['msforms', 'MSForms'],
];

const out = {};
for (const [folder, library] of LIBRARIES) {
	const file = path.join(root, 'reference', folder, 'eventSources.json');
	const dump = JSON.parse(fs.readFileSync(file, 'utf8'));
	for (const [className, interfaceName] of Object.entries(dump.classes)) {
		// MSForms repeats each control as "<Name>2", and its HTML controls are
		// no UserForm's.
		if (library === 'MSForms' && (/2$/.test(className) || className.startsWith('HTML'))) {
			continue;
		}
		const events = {};
		for (const event of dump.interfaces[interfaceName]) {
			events[event.name] = event.params
				.map((param) => `${param.byVal ? 'ByVal ' : ''}${param.name} As ${param.type}`)
				.join(', ');
		}
		out[`${library}.${className}`] = events;
	}
}

const lines = [
	'// Generated by scripts/generate-event-signatures.mjs from the event',
	'// interfaces of the Office type libraries. Do not edit by hand.',
	'//',
	'// Each class\'s events with their parameters as VBA declares them, ByVal',
	'// where the library passes by value: a handler must match (issue #195).',
	'',
	'export const HOST_EVENT_SIGNATURES: Readonly<Record<string, Readonly<Record<string, string>>>> = {',
];
for (const className of Object.keys(out).sort()) {
	lines.push(`\t'${className}': {`);
	for (const [event, params] of Object.entries(out[className])) {
		lines.push(`\t\t${event}: '${params}',`);
	}
	lines.push('\t},');
}
lines.push('};', '');
const target = path.join(root, 'src', 'analyzer', 'host', 'eventSignaturesData.ts');
fs.writeFileSync(target, lines.join('\n'));
const events = Object.values(out).reduce((sum, events) => sum + Object.keys(events).length, 0);
console.log(`${path.relative(root, target)}: ${Object.keys(out).length} classes, ${events} events`);
