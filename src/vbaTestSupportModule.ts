/**
 * The text two copies of the support module are compared by, for the "is the
 * installed XlideAssert the one we ship?" gate.
 *
 * Identifier CASE is folded away, because VBA owns it: a declaration anywhere
 * in the project - a user's own `Dim value` - re-cases every matching
 * identifier in every module, including this one, without changing what the
 * code means (issue #38). Comparing case-sensitively read such a module as a
 * version drift and offered to reinstall a module that was already current.
 *
 * Only identifiers fold. String literals and comments are compared verbatim,
 * because VBA never rewrites those, so a difference there is a real edit.
 */
export function normalizeVbaTestSupportModuleSource(source: string): string {
    const text = normalizeEol(source)
        .split('\n')
        .filter((line) => !isVbaAttributeLine(line))
        .join('\n')
        .trim();
    return foldIdentifierCase(text);
}

const CASE_INSENSITIVE_TOKEN_KINDS = new Set(['identifier', 'keyword', 'bracketedIdentifier']);

/** Lowercases identifier-like tokens in place, leaving all other text as written. */
function foldIdentifierCase(source: string): string {
    let out = '';
    let index = 0;
    for (const token of tokenize(source)) {
        if (!CASE_INSENSITIVE_TOKEN_KINDS.has(token.kind)) {
            continue;
        }
        out += source.slice(index, token.start) + token.rawText.toLowerCase();
        index = token.end;
    }
    return out + source.slice(index);
}
