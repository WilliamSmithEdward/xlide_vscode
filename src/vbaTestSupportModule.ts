// IDENTIFIER CASING IS PART OF THIS MODULE'S CONTRACT. VBA cases identifiers
// project-wide to the latest declaration it sees, so every name declared here
// that also exists in a host object model or the VBA runtime must be spelled
// the way that model spells it - `Value`, `Message`, `Number`, `Source`,
// `Condition`, `MacroName`. A lowercase parameter re-spells every `.Value` and
// `Err.Number` in the user's project the moment XlideAssert is installed, and
// XlideAssert is installed permanently (issue #38).
// tests/vbaTestModuleIdentifierCasing.test.ts enforces this mechanically.

